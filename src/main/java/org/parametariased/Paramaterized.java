package org.parametariased;

public class Paramaterized {
    public static void main(String[] args) {
        add(12, 34);
        sub(12, 6);

    }

    public static void add(int a, int b) {
        System.out.println(a + b);
    }

    public static void sub(int a, int b) {
        System.out.println(a - b);
    }
}

